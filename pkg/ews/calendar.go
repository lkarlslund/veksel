// maxExpandedOccurrences bounds the instances one recurring event yields
// for a CalendarView or an InstanceIndex lookup.
const maxExpandedOccurrences = 5000

// eventData is one decoded iCalendar resource: the master VEVENT and its
// RECURRENCE-ID overrides.
type eventData struct {
	cal       *ical.Calendar
	master    *ical.Component
	overrides []*ical.Component
}

func parseEvent(data []byte) *eventData {
	cal, err := calendar.NewDecoder(data).Decode()
	if err != nil {
		return nil
	}
	event := &eventData{cal: cal}
	for _, child := range cal.Children {
		if child.Name != ical.CompEvent {
			continue
		}
		if child.Props.Get(ical.PropRecurrenceID) != nil {
			event.overrides = append(event.overrides, child)
		} else if event.master == nil {
			event.master = child
		}
	}
	if event.master == nil {
		if len(event.overrides) == 0 {
			return nil
		}
		event.master, event.overrides = event.overrides[0], event.overrides[1:]
	}
	return event
}

func newEvent(uid string) *eventData {
	cal := ical.NewCalendar()
	cal.Props.SetText(ical.PropVersion, "2.0")
	cal.Props.SetText(ical.PropProductID, "-//Veksel//EWS//EN")
	master := ical.NewEvent()
	if uid == "" {
		uid = newUID()
	}
	master.Props.SetText(ical.PropUID, uid)
	master.Props.SetDateTime(ical.PropCreated, time.Now().UTC())
	cal.Children = append(cal.Children, master.Component)
	return &eventData{cal: cal, master: master.Component}
}

func (e *eventData) encode() ([]byte, map[string]string, error) {
	calendar.AddMissingTimezones(e.cal)
	var buffer bytes.Buffer
	if err := ical.NewEncoder(&buffer).Encode(e.cal); err != nil {
		return nil, nil, err
	}
	uid, _ := e.master.Props.Text(ical.PropUID)
	summary, _ := e.master.Props.Text(ical.PropSummary)
	return buffer.Bytes(), map[string]string{"UID": uid, "SUMMARY": summary}, nil
}

func newUID() string {
	value := make([]byte, 16)
	_, _ = rand.Read(value)
	return hex.EncodeToString(value) + "@veksel"
}

// propTime reads a DATE or DATE-TIME property. TZIDs may be IANA or
// Windows names; unknown TZIDs and floating times are read in fallback.
func propTime(prop *ical.Prop, fallback *time.Location) (value time.Time, allDay bool, location *time.Location, ok bool) {
	if prop == nil {
		return time.Time{}, false, nil, false
	}
	if fallback == nil {
		fallback = time.UTC
	}
	text := strings.TrimSpace(prop.Value)
	if prop.ValueType() == ical.ValueDate || len(text) == 8 {
		parsed, err := time.ParseInLocation("20060102", text, fallback)
		return parsed, true, fallback, err == nil
	}
	location = fallback
	if strings.HasSuffix(text, "Z") {
		location = time.UTC
	} else if tzid := prop.Params.Get(ical.PropTimezoneID); tzid != "" {
		if loaded := zoneLocation(tzid); loaded != nil {
			location = loaded
		}
	}
	parsed, err := time.ParseInLocation("20060102T150405", strings.TrimSuffix(text, "Z"), location)
	return parsed, false, location, err == nil
}

// componentTimes resolves a component's start and end and the zone it is
// described in.
func componentTimes(component *ical.Component, fallback *time.Location) (start, end time.Time, allDay bool, location *time.Location, ok bool) {
	start, allDay, location, ok = propTime(component.Props.Get(ical.PropDateTimeStart), fallback)
	if !ok {
		return time.Time{}, time.Time{}, false, fallback, false
	}
	end, _, _, endOK := propTime(component.Props.Get(ical.PropDateTimeEnd), location)
	if !endOK {
		if prop := component.Props.Get(ical.PropDuration); prop != nil {
			if duration, err := prop.Duration(); err == nil {
				end, endOK = start.Add(duration), true
			}
		}
	}
	if !endOK || end.Before(start) {
		end = start
		if allDay {
			end = start.AddDate(0, 0, 1)
		}
	}
	return start, end, allDay, location, true
}

// occurrenceKey identifies an instance of a recurring event by its
// original start: the local date for all-day events, the UTC instant
// otherwise.
func occurrenceKey(original time.Time, allDay bool) string {
	if allDay {
		return original.Format("20060102")
	}
	return original.UTC().Format("20060102T150405Z")
}

func encodeOccurrenceID(itemID, key string) string {
	return encodeID("o:", itemID+"\x00"+key)
}

// occurrence is one instance of an event.
type occurrence struct {
	key        string
	original   time.Time
	start, end time.Time
	// override is the RECURRENCE-ID component of an exception, nil for an
	// instance generated by the rule.
	override *ical.Component
}

// recurrence returns the event's rule set and the master's timing; set is
// nil for a single event.
func (e *eventData) recurrence(zone *time.Location) (set *rrule.Set, start time.Time, duration time.Duration, allDay bool, location *time.Location) {
	start, end, allDay, location, ok := componentTimes(e.master, zone)
	if !ok {
		return nil, time.Time{}, 0, false, zone
	}
	duration = end.Sub(start)
	option, err := e.master.Props.RecurrenceRule()
	if err != nil || option == nil {
		return nil, start, duration, allDay, location
	}
	option.Dtstart = start
	rule, err := rrule.NewRRule(*option)
	if err != nil {
		return nil, start, duration, allDay, location
	}
	set = &rrule.Set{}
	set.RRule(rule)
	set.DTStart(start)
	for _, name := range []string{ical.PropExceptionDates, ical.PropRecurrenceDates} {
		for _, value := range splitDates(e.master.Props.Values(name)) {
			instant, _, _, ok := propTime(value, location)
			if !ok {
				continue
			}
			if name == ical.PropExceptionDates {
				set.ExDate(instant)
			} else {
				set.RDate(instant)
			}
		}
	}
	return set, start, duration, allDay, location
}

// splitDates expands comma-separated EXDATE and RDATE values.
func splitDates(props []ical.Prop) []*ical.Prop {
	var result []*ical.Prop
	for _, prop := range props {
		for _, value := range strings.Split(prop.Value, ",") {
			single := prop
			single.Value = strings.TrimSpace(value)
			result = append(result, &single)
		}
	}
	return result
}

// overrideKeys maps each override to its occurrence key.
func (e *eventData) overrideKeys(location *time.Location, allDay bool) map[string]*ical.Component {
	keys := make(map[string]*ical.Component, len(e.overrides))
	for _, override := range e.overrides {
		original, _, _, ok := propTime(override.Props.Get(ical.PropRecurrenceID), location)
		if ok {
			keys[occurrenceKey(original, allDay)] = override
		}
	}
	return keys
}

func cancelled(component *ical.Component) bool {
	status, _ := component.Props.Text(ical.PropStatus)
	return strings.EqualFold(status, "CANCELLED")
}

// occurrencesBetween lists the instances overlapping [from, to), sorted
// by start. A single event yields itself with an empty key.
func (e *eventData) occurrencesBetween(zone *time.Location, from, to time.Time) []occurrence {
	set, start, duration, allDay, location := e.recurrence(zone)
	if set == nil {
		if start.IsZero() || cancelled(e.master) {
			return nil
		}
		end := start.Add(duration)
		if start.Before(to) && (end.After(from) || end.Equal(start) && !start.Before(from)) {
			return []occurrence{{start: start, end: end}}
		}
		return nil
	}
	overrides := e.overrideKeys(location, allDay)
	var result []occurrence
	seen := map[string]bool{}
	for _, instant := range set.Between(from.Add(-duration), to, true) {
		if len(result) >= maxExpandedOccurrences {
			break
		}
		key := occurrenceKey(instant, allDay)
		seen[key] = true
		if override := overrides[key]; override != nil {
			continue
		}
		end := instant.Add(duration)
		if instant.Before(to) && end.After(from) {
			result = append(result, occurrence{key: key, original: instant, start: instant, end: end})
		}
	}
	for key, override := range overrides {
		if cancelled(override) {
			continue
		}
		overrideStart, overrideEnd, _, _, ok := componentTimes(override, location)
		if !ok || !overrideStart.Before(to) || !overrideEnd.After(from) {
			continue
		}
		original, _, _, _ := propTime(override.Props.Get(ical.PropRecurrenceID), location)
		result = append(result, occurrence{key: key, original: original, start: overrideStart, end: overrideEnd, override: override})
	}
	sort.SliceStable(result, func(i, j int) bool { return result[i].start.Before(result[j].start) })
	return result
}

// occurrenceAt finds the instance with key.
func (e *eventData) occurrenceAt(key string, zone *time.Location) (occurrence, bool) {
	set, _, duration, allDay, location := e.recurrence(zone)
	if set == nil {
		return occurrence{}, false
	}
	if override := e.overrideKeys(location, allDay)[key]; override != nil {
		start, end, _, _, _ := componentTimes(override, location)
		original, _, _, _ := propTime(override.Props.Get(ical.PropRecurrenceID), location)
		return occurrence{key: key, original: original, start: start, end: end, override: override}, true
	}
	var original time.Time
	if allDay {
		parsed, err := time.ParseInLocation("20060102", key, location)
		if err != nil {
			return occurrence{}, false
		}
		original = parsed
	} else {
		parsed, err := time.Parse("20060102T150405Z", key)
		if err != nil {
			return occurrence{}, false
		}
		original = parsed
	}
	for _, instant := range set.Between(original.Add(-time.Second), original.Add(time.Second), true) {
		if occurrenceKey(instant, allDay) == key {
			return occurrence{key: key, original: instant, start: instant, end: instant.Add(duration)}, true
		}
	}
	return occurrence{}, false
}

// nthOccurrence finds the 1-based InstanceIndex of an OccurrenceItemId.
func (e *eventData) nthOccurrence(index int, zone *time.Location) (occurrence, bool) {
	set, _, _, allDay, _ := e.recurrence(zone)
	if set == nil || index < 1 || index > maxExpandedOccurrences {
		return occurrence{}, false
	}
	next := set.Iterator()
	for position := 1; ; position++ {
		instant, ok := next()
		if !ok {
			return occurrence{}, false
		}
		if position == index {
			return e.occurrenceAt(occurrenceKey(instant, allDay), zone)
		}
	}
}

// calendarInstance is what one CalendarItem element describes: a single
// event, a recurring master, or one occurrence or exception of it.
type calendarInstance struct {
	component  *ical.Component
	start, end time.Time
	allDay     bool
	location   *time.Location
	kind       string
	original   time.Time
	id         string
}

func masterInstance(item model.Item, event *eventData, zone *time.Location) calendarInstance {
	start, end, allDay, location, _ := componentTimes(event.master, zone)
	kind := "Single"
	if event.master.Props.Get(ical.PropRecurrenceRule) != nil {
		kind = "RecurringMaster"
	}
	return calendarInstance{component: event.master, start: start, end: end, allDay: allDay, location: location, kind: kind, id: encodeID("i:", item.ID)}
}

func occurrenceInstance(item model.Item, event *eventData, found occurrence, zone *time.Location) calendarInstance {
	_, _, allDay, location, _ := componentTimes(event.master, zone)
	instance := calendarInstance{component: event.master, start: found.start, end: found.end, allDay: allDay, location: location, kind: "Occurrence", original: found.original, id: encodeOccurrenceID(item.ID, found.key)}
	if found.override != nil {
		instance.component, instance.kind = found.override, "Exception"
		if _, _, overrideAllDay, _, ok := componentTimes(found.override, location); ok {
			instance.allDay = overrideAllDay
		}
	}
	return instance
}

// renderCalendarItem renders a calendar item, or one of its occurrences
// when key is set, in ItemType/CalendarItemType schema order.
func renderCalendarItem(item model.Item, shape itemShape, key string) string {
	event := parseEvent(item.Data)
	if event == nil {
		return `<t:CalendarItem><t:ItemId Id="` + encodeID("i:", item.ID) + `" ChangeKey="` + strconv.FormatUint(item.ModSeq, 10) + `"/><t:ParentFolderId Id="` + encodeID("f:", item.FolderID) + `"/><t:ItemClass>IPM.Appointment</t:ItemClass></t:CalendarItem>`
	}
	instance := masterInstance(item, event, shape.zone)
	if key != "" {
		found, ok := event.occurrenceAt(key, shape.zone)
		if !ok {
			return ""
		}
		instance = occurrenceInstance(item, event, found, shape.zone)
	}
	return renderCalendarInstance(item, event, instance, shape)
}

func renderCalendarInstance(item model.Item, event *eventData, instance calendarInstance, shape itemShape) string {
	component, master := instance.component, event.master
	props := component.Props
	organizer, organizerName := "", ""
	if prop := master.Props.Get(ical.PropOrganizer); prop != nil {
		organizer, organizerName = calendar.MailAddress(prop.Value), prop.Params.Get(ical.ParamCommonName)
	}
	attendees := master.Props.Values(ical.PropAttendee)
	if len(props.Values(ical.PropAttendee)) > 0 {
		attendees = props.Values(ical.PropAttendee)
	}
	meeting := organizer != "" && len(attendees) > 0
	organizing := !meeting || shape.profile.owns(organizer)
	isCancelled := cancelled(component) || cancelled(master)
	minutes, reminder := reminderMinutes(component)
	var required, optional, resources strings.Builder
	var displayTo []string
	for _, attendee := range attendees {
		address := calendar.MailAddress(attendee.Value)
		if address == "" || address == organizer {
			continue
		}
		name := attendee.Params.Get(ical.ParamCommonName)
		entry := `<t:Attendee>` + mailboxXML(name, address) + `<t:ResponseType>` + responseType(attendee.Params.Get(ical.ParamParticipationStatus)) + `</t:ResponseType></t:Attendee>`
		switch attendeeGroup(attendee.Params) {
		case "Resources":
			resources.WriteString(entry)
		case "OptionalAttendees":
			optional.WriteString(entry)
		default:
			required.WriteString(entry)
		}
		displayTo = append(displayTo, firstNonEmpty(name, address))
	}

	var out strings.Builder
	out.WriteString(`<t:CalendarItem>`)
	if shape.mime {
		out.WriteString(`<t:MimeContent CharacterSet="UTF-8">` + base64.StdEncoding.EncodeToString(item.Data) + `</t:MimeContent>`)
	}
	summary, _ := props.Text(ical.PropSummary)
	description, _ := props.Text(ical.PropDescription)
	common := itemCommon{
		item: item, id: instance.id, class: "IPM.Appointment", subject: summary, sensitivity: sensitivityName(props),
		body: description, categories: categoryList(props), importance: importanceName(props),
		reminderSet: reminder, reminderMinutes: minutes, reminderDue: instance.start.Add(-time.Duration(minutes) * time.Minute),
		displayTo: strings.Join(displayTo, "; "),
	}
	if created, _, _, ok := propTime(master.Props.Get(ical.PropCreated), time.UTC); ok {
		common.created = created
	}
	if modified, _, _, ok := propTime(props.Get(ical.PropLastModified), time.UTC); ok {
		common.modified = modified
	}
	switch {
	case meeting && !organizing:
		common.responseObjects = `<t:AcceptItem/><t:TentativelyAcceptItem/><t:DeclineItem/><t:ReplyToItem/><t:ReplyAllToItem/><t:ForwardItem/>`
	case meeting:
		common.responseObjects = `<t:CancelCalendarItem/><t:ForwardItem/>`
	default:
		common.responseObjects = `<t:ForwardItem/>`
	}
	out.WriteString(common.render(shape))

	uid, _ := master.Props.Text(ical.PropUID)
	out.WriteString(`<t:UID>` + escape(uid) + `</t:UID>`)
	if instance.kind == "Occurrence" || instance.kind == "Exception" {
		out.WriteString(`<t:RecurrenceId>` + formatDateTime(instance.original) + `</t:RecurrenceId>`)
	}
	stamp := item.UpdatedAt
	if value, _, _, ok := propTime(props.Get(ical.PropDateTimeStamp), time.UTC); ok {
		stamp = value
	}
	out.WriteString(`<t:DateTimeStamp>` + formatDateTime(stamp) + `</t:DateTimeStamp>`)
	out.WriteString(`<t:Start>` + formatDateTime(instance.start) + `</t:Start><t:End>` + formatDateTime(instance.end) + `</t:End>`)
	if instance.kind == "Occurrence" || instance.kind == "Exception" {
		out.WriteString(`<t:OriginalStart>` + formatDateTime(instance.original) + `</t:OriginalStart>`)
	}
	out.WriteString(`<t:IsAllDayEvent>` + strconv.FormatBool(instance.allDay) + `</t:IsAllDayEvent><t:LegacyFreeBusyStatus>` + freeBusyStatus(props) + `</t:LegacyFreeBusyStatus>`)
	if location, _ := props.Text(ical.PropLocation); location != "" {
		out.WriteString(`<t:Location>` + escape(location) + `</t:Location>`)
	}
	out.WriteString(`<t:IsMeeting>` + strconv.FormatBool(meeting) + `</t:IsMeeting><t:IsCancelled>` + strconv.FormatBool(isCancelled) + `</t:IsCancelled>`)
	out.WriteString(`<t:IsRecurring>` + strconv.FormatBool(instance.kind != "Single") + `</t:IsRecurring>`)
	out.WriteString(`<t:MeetingRequestWasSent>` + strconv.FormatBool(meeting && organizing) + `</t:MeetingRequestWasSent><t:IsResponseRequested>` + strconv.FormatBool(meeting && !organizing) + `</t:IsResponseRequested>`)
	out.WriteString(`<t:CalendarItemType>` + instance.kind + `</t:CalendarItemType><t:MyResponseType>` + myResponseType(attendees, shape.profile, meeting, organizing) + `</t:MyResponseType>`)
	if organizer != "" {
		out.WriteString(`<t:Organizer>` + mailboxXML(organizerName, organizer) + `</t:Organizer>`)
	}
	if required.Len() > 0 {
		out.WriteString(`<t:RequiredAttendees>` + required.String() + `</t:RequiredAttendees>`)
	}
	if optional.Len() > 0 {
		out.WriteString(`<t:OptionalAttendees>` + optional.String() + `</t:OptionalAttendees>`)
	}
	if resources.Len() > 0 {
		out.WriteString(`<t:Resources>` + resources.String() + `</t:Resources>`)
	}
	out.WriteString(`<t:Duration>` + formatXSDuration(instance.end.Sub(instance.start)) + `</t:Duration>`)
	zoneName := windowsZone(instance.location, instance.start.Year())
	out.WriteString(`<t:TimeZone>` + escape(zoneName) + `</t:TimeZone>`)
	sequence := 0
	if prop := props.Get(ical.PropSequence); prop != nil {
		sequence, _ = prop.Int()
	}
	state := 0
	if meeting {
		state = 1
		if !organizing {
			state |= 2
		}
		if isCancelled {
			state |= 4
		}
	}
	out.WriteString(`<t:AppointmentSequenceNumber>` + strconv.Itoa(sequence) + `</t:AppointmentSequenceNumber><t:AppointmentState>` + strconv.Itoa(state) + `</t:AppointmentState>`)
	if instance.kind == "RecurringMaster" {
		if rule := master.Props.Get(ical.PropRecurrenceRule); rule != nil {
			out.WriteString(recurrenceXML(rule.Value, instance.start.In(instance.location), instance.allDay, instance.location))
		}
		modified, deleted := occurrenceLists(item, event, instance)
		if modified != "" {
			out.WriteString(`<t:ModifiedOccurrences>` + modified + `</t:ModifiedOccurrences>`)
		}
		if deleted != "" {
			out.WriteString(`<t:DeletedOccurrences>` + deleted + `</t:DeletedOccurrences>`)
		}
	}
	out.WriteString(timeZoneElements(shape.info, instance.location, instance.start.Year()))
	out.WriteString(`<t:AllowNewTimeProposal>true</t:AllowNewTimeProposal></t:CalendarItem>`)
	return out.String()
}

// occurrenceLists renders a master's ModifiedOccurrences and
// DeletedOccurrences.
func occurrenceLists(item model.Item, event *eventData, master calendarInstance) (string, string) {
	var modified, deleted strings.Builder
	var deletedTimes []time.Time
	for _, value := range splitDates(event.master.Props.Values(ical.PropExceptionDates)) {
		if instant, _, _, ok := propTime(value, master.location); ok {
			deletedTimes = append(deletedTimes, instant)
		}
	}
	type modifiedEntry struct {
		key                  string
		original, start, end time.Time
	}
	var entries []modifiedEntry
	for _, override := range event.overrides {
		original, _, _, ok := propTime(override.Props.Get(ical.PropRecurrenceID), master.location)
		if !ok {
			continue
		}
		if cancelled(override) {
			deletedTimes = append(deletedTimes, original)
			continue
		}
		start, end, _, _, ok := componentTimes(override, master.location)
		if !ok {
			continue
		}
		entries = append(entries, modifiedEntry{key: occurrenceKey(original, master.allDay), original: original, start: start, end: end})
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].original.Before(entries[j].original) })
	for _, entry := range entries {
		modified.WriteString(`<t:Occurrence><t:ItemId Id="` + encodeOccurrenceID(item.ID, entry.key) + `" ChangeKey="` + strconv.FormatUint(item.ModSeq, 10) + `"/><t:Start>` + formatDateTime(entry.start) + `</t:Start><t:End>` + formatDateTime(entry.end) + `</t:End><t:OriginalStart>` + formatDateTime(entry.original) + `</t:OriginalStart></t:Occurrence>`)
	}
	slices.SortFunc(deletedTimes, func(a, b time.Time) int { return a.Compare(b) })
	for _, instant := range deletedTimes {
		deleted.WriteString(`<t:DeletedOccurrence><t:Start>` + formatDateTime(instant) + `</t:Start></t:DeletedOccurrence>`)
	}
	return modified.String(), deleted.String()
}

func mailboxXML(name, address string) string {
	out := `<t:Mailbox>`
	if name != "" {
		out += `<t:Name>` + escape(name) + `</t:Name>`
	}
	return out + `<t:EmailAddress>` + escape(address) + `</t:EmailAddress><t:RoutingType>SMTP</t:RoutingType></t:Mailbox>`
}

func attendeeGroup(params ical.Params) string {
	cuType := strings.ToUpper(params.Get(ical.ParamCalendarUserType))
	switch {
	case cuType == "RESOURCE" || cuType == "ROOM":
		return "Resources"
	case strings.EqualFold(params.Get(ical.ParamRole), "OPT-PARTICIPANT") || strings.EqualFold(params.Get(ical.ParamRole), "NON-PARTICIPANT"):
		return "OptionalAttendees"
	}
	return "RequiredAttendees"
}

func responseType(partStat string) string {
	switch strings.ToUpper(strings.TrimSpace(partStat)) {
	case "ACCEPTED":
		return "Accept"
	case "TENTATIVE":
		return "Tentative"
	case "DECLINED":
		return "Decline"
	case "NEEDS-ACTION", "":
		return "NoResponseReceived"
	}
	return "Unknown"
}

func myResponseType(attendees []ical.Prop, profile Profile, meeting, organizing bool) string {
	if !meeting || organizing {
		return "Organizer"
	}
	for _, attendee := range attendees {
		if profile.owns(calendar.MailAddress(attendee.Value)) {
			return responseType(attendee.Params.Get(ical.ParamParticipationStatus))
		}
	}
	return "Unknown"
}

func reminderMinutes(component *ical.Component) (int, bool) {
	for _, child := range component.Children {
		if child.Name != ical.CompAlarm {
			continue
		}
		trigger := child.Props.Get(ical.PropTrigger)
		if trigger == nil || trigger.ValueType() == ical.ValueDateTime || strings.EqualFold(trigger.Params.Get(ical.ParamRelated), "END") {
			continue
		}
		if duration, err := trigger.Duration(); err == nil && duration <= 0 {
			return int(-duration / time.Minute), true
		}
	}
	return 0, false
}

func sensitivityName(props ical.Props) string {
	value, _ := props.Text(ical.PropClass)
	switch strings.ToUpper(value) {
	case "PRIVATE":
		return "Private"
	case "CONFIDENTIAL":
		return "Confidential"
	}
	return "Normal"
}

func importanceName(props ical.Props) string {
	if prop := props.Get(ical.PropPriority); prop != nil {
		if priority, err := prop.Int(); err == nil {
			switch {
			case priority >= 1 && priority <= 4:
				return "High"
			case priority >= 6:
				return "Low"
			}
		}
	}
	return "Normal"
}

func freeBusyStatus(props ical.Props) string {
	if value, _ := props.Text("X-MICROSOFT-CDO-BUSYSTATUS"); value != "" {
		switch strings.ToUpper(value) {
		case "FREE":
			return "Free"
		case "TENTATIVE":
			return "Tentative"
		case "OOF":
			return "OOF"
		case "WORKINGELSEWHERE":
			return "WorkingElsewhere"
		}
		return "Busy"
	}
	if value, _ := props.Text(ical.PropTransparency); strings.EqualFold(value, "TRANSPARENT") {
		return "Free"
	}
	if value, _ := props.Text(ical.PropStatus); strings.EqualFold(value, "TENTATIVE") {
		return "Tentative"
	}
	return "Busy"
}

func categoryList(props ical.Props) []string {
	var values []string
	for _, prop := range props.Values(ical.PropCategories) {
		list, _ := prop.TextList()
		for _, value := range list {
			if value = strings.TrimSpace(value); value != "" {
				values = append(values, value)
			}
		}
	}
	return values
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if strings.TrimSpace(value) != "" {
			return strings.TrimSpace(value)
		}
	}
	return ""
}

// rruleParts splits an RRULE value into upper-cased parts.
func rruleParts(value string) map[string]string {
	parts := map[string]string{}
	for _, part := range strings.Split(value, ";") {
		key, val, ok := strings.Cut(part, "=")
		if ok {
			parts[strings.ToUpper(strings.TrimSpace(key))] = strings.ToUpper(strings.TrimSpace(val))
		}
	}
	return parts
}

var weekdayCodes = []string{"SU", "MO", "TU", "WE", "TH", "FR", "SA"}

// byDayNames converts BYDAY into EWS DaysOfWeek and the ordinal (0 when
// absent).
func byDayNames(value string) (string, int) {
	var names []string
	ordinal := 0
	for _, entry := range strings.Split(value, ",") {
		entry = strings.TrimSpace(entry)
		if len(entry) < 2 {
			continue
		}
		code := entry[len(entry)-2:]
		if prefix := entry[:len(entry)-2]; prefix != "" {
			ordinal, _ = strconv.Atoi(prefix)
		}
		if index := slices.Index(weekdayCodes, code); index >= 0 {
			names = append(names, weekdayNames[index])
		}
	}
	joined := strings.Join(names, " ")
	switch joined {
	case "Monday Tuesday Wednesday Thursday Friday":
		joined = "Weekday"
	case "Sunday Saturday", "Saturday Sunday":
		joined = "WeekendDay"
	case "Sunday Monday Tuesday Wednesday Thursday Friday Saturday":
		joined = "Day"
	}
	return joined, ordinal
}

// recurrenceXML renders an RRULE as an EWS Recurrence: a pattern and a
// range. Rules EWS cannot express are approximated by their frequency.
func recurrenceXML(value string, localStart time.Time, allDay bool, location *time.Location) string {
	rule := rruleParts(value)
	interval := rule["INTERVAL"]
	if interval == "" {
		interval = "1"
	}
	days, ordinal := byDayNames(rule["BYDAY"])
	if position, err := strconv.Atoi(rule["BYSETPOS"]); err == nil && ordinal == 0 {
		ordinal = position
	}
	month := localStart.Month()
	if value, err := strconv.Atoi(rule["BYMONTH"]); err == nil && value >= 1 && value <= 12 {
		month = time.Month(value)
	}
	dayOfMonth := strconv.Itoa(localStart.Day())
	if value := rule["BYMONTHDAY"]; value != "" && !strings.Contains(value, ",") {
		dayOfMonth = value
		if value == "-1" {
			dayOfMonth = "31"
		}
	}
	var pattern string
	switch rule["FREQ"] {
	case "DAILY":
		if days != "" {
			pattern = `<t:WeeklyRecurrence><t:Interval>` + interval + `</t:Interval><t:DaysOfWeek>` + expandDayNames(days) + `</t:DaysOfWeek></t:WeeklyRecurrence>`
		} else {
			pattern = `<t:DailyRecurrence><t:Interval>` + interval + `</t:Interval></t:DailyRecurrence>`
		}
	case "WEEKLY":
		if days == "" {
			days = weekdayNames[localStart.Weekday()]
		}
		pattern = `<t:WeeklyRecurrence><t:Interval>` + interval + `</t:Interval><t:DaysOfWeek>` + expandDayNames(days) + `</t:DaysOfWeek></t:WeeklyRecurrence>`
	case "MONTHLY":
		if days != "" && ordinal != 0 {
			pattern = `<t:RelativeMonthlyRecurrence><t:Interval>` + interval + `</t:Interval><t:DaysOfWeek>` + days + `</t:DaysOfWeek><t:DayOfWeekIndex>` + dayIndexName(ordinal) + `</t:DayOfWeekIndex></t:RelativeMonthlyRecurrence>`
		} else {
			pattern = `<t:AbsoluteMonthlyRecurrence><t:Interval>` + interval + `</t:Interval><t:DayOfMonth>` + dayOfMonth + `</t:DayOfMonth></t:AbsoluteMonthlyRecurrence>`
		}
	case "YEARLY":
		if days != "" && ordinal != 0 {
			pattern = `<t:RelativeYearlyRecurrence><t:DaysOfWeek>` + days + `</t:DaysOfWeek><t:DayOfWeekIndex>` + dayIndexName(ordinal) + `</t:DayOfWeekIndex><t:Month>` + monthNames[month-1] + `</t:Month></t:RelativeYearlyRecurrence>`
		} else {
			pattern = `<t:AbsoluteYearlyRecurrence><t:DayOfMonth>` + dayOfMonth + `</t:DayOfMonth><t:Month>` + monthNames[month-1] + `</t:Month></t:AbsoluteYearlyRecurrence>`
		}
	default:
		return ""
	}
	startDate := localStart.Format("2006-01-02")
	var rangeXML string
	switch {
	case rule["COUNT"] != "":
		rangeXML = `<t:NumberedRecurrence><t:StartDate>` + startDate + `</t:StartDate><t:NumberOfOccurrences>` + rule["COUNT"] + `</t:NumberOfOccurrences></t:NumberedRecurrence>`
	case rule["UNTIL"] != "":
		until, ok := parseUntil(rule["UNTIL"], location)
		if !ok {
			until = localStart
		}
		rangeXML = `<t:EndDateRecurrence><t:StartDate>` + startDate + `</t:StartDate><t:EndDate>` + until.In(location).Format("2006-01-02") + `</t:EndDate></t:EndDateRecurrence>`
	default:
		rangeXML = `<t:NoEndRecurrence><t:StartDate>` + startDate + `</t:StartDate></t:NoEndRecurrence>`
	}
	_ = allDay
	return `<t:Recurrence>` + pattern + rangeXML + `</t:Recurrence>`
}

// expandDayNames lists the days of a weekly pattern individually, which
// every client understands.
func expandDayNames(days string) string {
	switch days {
	case "Weekday":
		return "Monday Tuesday Wednesday Thursday Friday"
	case "WeekendDay":
		return "Saturday Sunday"
	case "Day":
		return "Sunday Monday Tuesday Wednesday Thursday Friday Saturday"
	}
	return days
}

func parseUntil(value string, location *time.Location) (time.Time, bool) {
	if location == nil {
		location = time.UTC
	}
	if parsed, err := time.Parse("20060102T150405Z", value); err == nil {
		return parsed, true
	}
	if parsed, err := time.ParseInLocation("20060102T150405", value, location); err == nil {
		return parsed, true
	}
	if parsed, err := time.ParseInLocation("20060102", value, location); err == nil {
		return parsed, true
	}
	return time.Time{}, false
}

// dayCodes converts EWS DaysOfWeek to BYDAY codes.
func dayCodes(value string) []string {
	var codes []string
	for _, token := range strings.Fields(value) {
		switch strings.ToLower(token) {
		case "day":
			codes = append(codes, weekdayCodes...)
		case "weekday":
			codes = append(codes, "MO", "TU", "WE", "TH", "FR")
		case "weekendday":
			codes = append(codes, "SA", "SU")
		default:
			for index, name := range weekdayNames {
				if strings.EqualFold(name, token) {
					codes = append(codes, weekdayCodes[index])
				}
			}
		}
	}
	return codes
}

// ruleFromRecurrence converts an EWS Recurrence to an RRULE value.
func ruleFromRecurrence(recurrence *node, allDay bool, location *time.Location) (string, error) {
	var parts []string
	var patternNode, rangeNode *node
	for _, child := range recurrence.Children {
		if strings.HasSuffix(child.Name.Local, "Recurrence") && (strings.HasPrefix(child.Name.Local, "NoEnd") || strings.HasPrefix(child.Name.Local, "EndDate") || strings.HasPrefix(child.Name.Local, "Numbered")) {
			rangeNode = child
		} else if strings.HasSuffix(child.Name.Local, "Recurrence") || strings.HasSuffix(child.Name.Local, "Regeneration") {
			patternNode = child
		}
	}
	if patternNode == nil {
		return "", fmt.Errorf("%w: Recurrence requires a pattern", errEWSInvalidProperty)
	}
	interval, _ := strconv.Atoi(patternNode.descendantText("Interval"))
	days := dayCodes(patternNode.descendantText("DaysOfWeek"))
	index := dayIndexNumber(patternNode.descendantText("DayOfWeekIndex"))
	month := monthNumber(patternNode.descendantText("Month"))
	dayOfMonth := patternNode.descendantText("DayOfMonth")
	relative := func() {
		if len(days) == 1 {
			parts = append(parts, "BYDAY="+strconv.Itoa(index)+days[0])
		} else if len(days) > 1 {
			parts = append(parts, "BYDAY="+strings.Join(days, ","), "BYSETPOS="+strconv.Itoa(index))
		}
	}
	switch patternNode.Name.Local {
	case "DailyRecurrence", "DailyRegeneration":
		parts = append(parts, "FREQ=DAILY")
	case "WeeklyRecurrence", "WeeklyRegeneration":
		parts = append(parts, "FREQ=WEEKLY")
		if len(days) > 0 {
			parts = append(parts, "BYDAY="+strings.Join(days, ","))
		}
		if first := dayCodes(patternNode.descendantText("FirstDayOfWeek")); len(first) == 1 {
			parts = append(parts, "WKST="+first[0])
		}
	case "AbsoluteMonthlyRecurrence", "MonthlyRegeneration":
		parts = append(parts, "FREQ=MONTHLY")
		if dayOfMonth != "" {
			parts = append(parts, "BYMONTHDAY="+dayOfMonth)
		}
	case "RelativeMonthlyRecurrence":
		parts = append(parts, "FREQ=MONTHLY")
		if index == 0 {
			return "", fmt.Errorf("%w: RelativeMonthlyRecurrence requires DayOfWeekIndex", errEWSInvalidProperty)
		}
		relative()
	case "AbsoluteYearlyRecurrence", "YearlyRegeneration":
		parts = append(parts, "FREQ=YEARLY")
		if month != 0 {
			parts = append(parts, "BYMONTH="+strconv.Itoa(month))
		}
		if dayOfMonth != "" {
			parts = append(parts, "BYMONTHDAY="+dayOfMonth)
		}
	case "RelativeYearlyRecurrence":
		parts = append(parts, "FREQ=YEARLY")
		if month != 0 {
			parts = append(parts, "BYMONTH="+strconv.Itoa(month))
		}
		if index == 0 {
			return "", fmt.Errorf("%w: RelativeYearlyRecurrence requires DayOfWeekIndex", errEWSInvalidProperty)
		}
		relative()
	default:
		return "", fmt.Errorf("%w: unsupported recurrence pattern %s", errEWSInvalidProperty, patternNode.Name.Local)
	}
	if interval > 1 {
		parts = append(parts, "INTERVAL="+strconv.Itoa(interval))
	}
	if rangeNode != nil {
		switch rangeNode.Name.Local {
		case "NumberedRecurrence":
			count, err := strconv.Atoi(rangeNode.descendantText("NumberOfOccurrences"))
			if err != nil || count < 1 {
				return "", fmt.Errorf("%w: NumberOfOccurrences must be positive", errEWSInvalidProperty)
			}
			parts = append(parts, "COUNT="+strconv.Itoa(count))
		case "EndDateRecurrence":
			text := rangeNode.descendantText("EndDate")
			if len(text) < 10 {
				return "", fmt.Errorf("%w: EndDate is required", errEWSInvalidProperty)
			}
			if location == nil {
				location = time.UTC
			}
			day, err := time.ParseInLocation("2006-01-02", text[:10], location)
			if err != nil {
				return "", fmt.Errorf("%w: invalid EndDate", errEWSInvalidProperty)
			}
			if allDay {
				parts = append(parts, "UNTIL="+day.Format("20060102"))
			} else {
				parts = append(parts, "UNTIL="+day.AddDate(0, 0, 1).Add(-time.Second).UTC().Format("20060102T150405Z"))
			}
		}
	}
	return strings.Join(parts, ";"), nil
}

// calendarContext is what applying CalendarItem properties needs to know
// about the request and the account.
type calendarContext struct {
	info    requestInfo
	profile Profile
	zone    *time.Location
	create  bool
}

// applyCalendarFields writes the CalendarItem properties in fields to
// component, the master or an override of event. Properties EWS does not
// model are preserved.
func applyCalendarFields(event *eventData, component *ical.Component, fields fieldChanges, scope calendarContext) error {
	isMaster := component == event.master
	props := component.Props
	before := significant(props)
	existingStart, existingEnd, existingAllDay, existingLocation, existingOK := componentTimes(component, scope.zone)

	var storeLocation *time.Location
	var parseZone localZone
	if definition := fields.set["StartTimeZone"]; definition != nil {
		if location := definitionLocation(definition); location != nil {
			storeLocation, parseZone = location, localZone{location: location}
		}
	}
	if !parseZone.known() {
		if zone := fields.set["MeetingTimeZone"]; zone != nil {
			parseZone = meetingTimeZone(zone)
			storeLocation = parseZone.location
		}
	}
	if storeLocation == nil && existingOK && !existingAllDay {
		storeLocation = existingLocation
	}
	if storeLocation == nil {
		storeLocation = scope.zone
	}
	if storeLocation == nil {
		storeLocation = time.UTC
	}
	if !parseZone.known() {
		if scope.info.zone != nil {
			parseZone = localZone{location: scope.info.zone}
		} else {
			parseZone = localZone{location: storeLocation}
		}
	}

	allDay := existingAllDay
	if value := fields.set["IsAllDayEvent"]; value != nil {
		allDay = parseBool(value.Text)
	}
	start, end := existingStart, existingEnd
	startSet, endSet := false, false
	if value := fields.set["Start"]; value != nil {
		parsed, ok := parseDateTime(value.Text, parseZone)
		if !ok {
			return fmt.Errorf("%w: invalid Start", errEWSInvalidProperty)
		}
		start, startSet = parsed, true
	}
	if value := fields.set["End"]; value != nil {
		parsed, ok := parseDateTime(value.Text, parseZone)
		if !ok {
			return fmt.Errorf("%w: invalid End", errEWSInvalidProperty)
		}
		end, endSet = parsed, true
	}
	if !existingOK && !startSet {
		return fmt.Errorf("%w: a calendar item requires Start", errEWSInvalidProperty)
	}
	if startSet && !endSet {
		switch {
		case existingOK:
			end = start.Add(existingEnd.Sub(existingStart))
		case allDay:
			end = start.AddDate(0, 0, 1)
		default:
			end = start.Add(30 * time.Minute)
		}
	}
	if end.Before(start) {
		return errEndBeforeStart
	}
	if startSet || endSet || fields.set["IsAllDayEvent"] != nil || fields.set["StartTimeZone"] != nil || fields.set["MeetingTimeZone"] != nil {
		setEventTimes(props, start, end, allDay, storeLocation)
	}

	setText := func(name, value string) {
		if strings.TrimSpace(value) == "" {
			props.Del(name)
			return
		}
		props.SetText(name, value)
	}
	if value := fields.set["Subject"]; value != nil {
		setText(ical.PropSummary, value.Text)
	} else if fields.deleted["Subject"] {
		props.Del(ical.PropSummary)
	}
	if value := fields.set["Body"]; value != nil {
		setText(ical.PropDescription, bodyText(value))
	} else if fields.deleted["Body"] {
		props.Del(ical.PropDescription)
	}
	if value := fields.set["Location"]; value != nil {
		setText(ical.PropLocation, value.Text)
	} else if fields.deleted["Location"] {
		props.Del(ical.PropLocation)
	}
	if value := fields.set["Sensitivity"]; value != nil {
		setSensitivity(props, value.Text)
	} else if fields.deleted["Sensitivity"] {
		props.Del(ical.PropClass)
	}
	if value := fields.set["Importance"]; value != nil {
		setImportance(props, value.Text)
	} else if fields.deleted["Importance"] {
		props.Del(ical.PropPriority)
	}
	if value := fields.set["Categories"]; value != nil {
		setCategories(props, stringList(value))
	} else if fields.deleted["Categories"] {
		props.Del(ical.PropCategories)
	}
	if value := fields.set["LegacyFreeBusyStatus"]; value != nil {
		setFreeBusy(props, value.Text)
	}
	if fields.has("ReminderIsSet") || fields.has("ReminderMinutesBeforeStart") {
		minutes, isSet := reminderMinutes(component)
		if !isSet {
			minutes = 15
		}
		if value := fields.set["ReminderIsSet"]; value != nil {
			isSet = parseBool(value.Text)
		} else if fields.deleted["ReminderIsSet"] {
			isSet = false
		}
		if value := fields.set["ReminderMinutesBeforeStart"]; value != nil {
			if parsed, err := strconv.Atoi(strings.TrimSpace(value.Text)); err == nil && parsed >= 0 {
				minutes = parsed
				if fields.set["ReminderIsSet"] == nil && scope.create {
					isSet = true
				}
			}
		}
		setReminder(component, isSet, minutes)
	}
	if isMaster {
		if value := fields.set["Recurrence"]; value != nil {
			rule, err := ruleFromRecurrence(value, allDay, storeLocation)
			if err != nil {
				return err
			}
			prop := ical.NewProp(ical.PropRecurrenceRule)
			prop.Value = rule
			props.Set(prop)
		} else if fields.deleted["Recurrence"] {
			props.Del(ical.PropRecurrenceRule)
			props.Del(ical.PropExceptionDates)
			props.Del(ical.PropRecurrenceDates)
			event.cal.Children = slices.DeleteFunc(event.cal.Children, func(child *ical.Component) bool {
				return child.Name == ical.CompEvent && child.Props.Get(ical.PropRecurrenceID) != nil
			})
			event.overrides = nil
		}
		applyAttendees(component, fields, scope.profile)
	}
	if after := significant(props); !scope.create && after != before && ownsOrganizer(event.master, scope.profile) {
		current := 0
		if prop := event.master.Props.Get(ical.PropSequence); prop != nil {
			current, _ = prop.Int()
		}
		for _, target := range append([]*ical.Component{event.master}, event.overrides...) {
			sequence := ical.NewProp(ical.PropSequence)
			sequence.Value = strconv.Itoa(current + 1)
			target.Props.Set(sequence)
		}
	}
	now := time.Now().UTC()
	props.SetDateTime(ical.PropDateTimeStamp, now)
	props.SetDateTime(ical.PropLastModified, now)
	return nil
}

var errEndBeforeStart = errors.New("the end date is earlier than the start date")

func ownsOrganizer(master *ical.Component, profile Profile) bool {
	prop := master.Props.Get(ical.PropOrganizer)
	return prop != nil && profile.owns(calendar.MailAddress(prop.Value))
}

func significant(props ical.Props) string {
	var parts []string
	for _, name := range []string{ical.PropDateTimeStart, ical.PropDateTimeEnd, ical.PropLocation, ical.PropRecurrenceRule, ical.PropExceptionDates} {
		for _, prop := range props.Values(name) {
			parts = append(parts, prop.Value+prop.Params.Get(ical.PropTimezoneID))
		}
		parts = append(parts, "|")
	}
	return strings.Join(parts, "")
}

// setEventTimes writes DTSTART and DTEND: dates in location for all-day
// events, times in location otherwise.
func setEventTimes(props ical.Props, start, end time.Time, allDay bool, location *time.Location) {
	props.Del(ical.PropDuration)
	if location == nil {
		location = time.UTC
	}
	if allDay {
		localStart, localEnd := start.In(location), end.In(location)
		startDate := time.Date(localStart.Year(), localStart.Month(), localStart.Day(), 0, 0, 0, 0, time.UTC)
		endDate := time.Date(localEnd.Year(), localEnd.Month(), localEnd.Day(), 0, 0, 0, 0, time.UTC)
		if !endDate.After(startDate) {
			endDate = startDate.AddDate(0, 0, 1)
		}
		props.SetDate(ical.PropDateTimeStart, startDate)
		props.SetDate(ical.PropDateTimeEnd, endDate)
		return
	}
	props.SetDateTime(ical.PropDateTimeStart, start.In(location))
	props.SetDateTime(ical.PropDateTimeEnd, end.In(location))
}

func setSensitivity(props ical.Props, value string) {
	switch strings.ToLower(strings.TrimSpace(value)) {
	case "private", "personal":
		props.SetText(ical.PropClass, "PRIVATE")
	case "confidential":
		props.SetText(ical.PropClass, "CONFIDENTIAL")
	default:
		props.Del(ical.PropClass)
	}
}

func setImportance(props ical.Props, value string) {
	priority := ""
	switch strings.ToLower(strings.TrimSpace(value)) {
	case "high":
		priority = "1"
	case "low":
		priority = "9"
	}
	if priority == "" {
		props.Del(ical.PropPriority)
		return
	}
	prop := ical.NewProp(ical.PropPriority)
	prop.Value = priority
	props.Set(prop)
}

func setCategories(props ical.Props, values []string) {
	props.Del(ical.PropCategories)
	if len(values) > 0 {
		prop := ical.NewProp(ical.PropCategories)
		prop.SetTextList(values)
		props.Set(prop)
	}
}

func setFreeBusy(props ical.Props, value string) {
	names := map[string]string{"free": "FREE", "tentative": "TENTATIVE", "busy": "BUSY", "oof": "OOF", "workingelsewhere": "WORKINGELSEWHERE"}
	name, ok := names[strings.ToLower(strings.TrimSpace(value))]
	if !ok {
		return
	}
	props.SetText("X-MICROSOFT-CDO-BUSYSTATUS", name)
	if name == "FREE" {
		props.SetText(ical.PropTransparency, "TRANSPARENT")
	} else {
		props.SetText(ical.PropTransparency, "OPAQUE")
	}
}

func setReminder(component *ical.Component, enabled bool, minutes int) {
	component.Children = slices.DeleteFunc(component.Children, func(child *ical.Component) bool { return child.Name == ical.CompAlarm })
	if !enabled {
		return
	}
	alarm := ical.NewComponent(ical.CompAlarm)
	alarm.Props.SetText(ical.PropAction, "DISPLAY")
	alarm.Props.SetText(ical.PropDescription, "Reminder")
	trigger := ical.NewProp(ical.PropTrigger)
	trigger.Value = "-PT" + strconv.Itoa(minutes) + "M"
	if minutes == 0 {
		trigger.Value = "PT0S"
	}
	alarm.Props.Set(trigger)
	component.Children = append(component.Children, alarm)
}

// applyAttendees replaces the attendee groups the request names. A client
// may only change the attendees of meetings the user organizes (or of new
// ones); for received meetings the organizer's list is authoritative.
func applyAttendees(master *ical.Component, fields fieldChanges, profile Profile) {
	groups := []string{"RequiredAttendees", "OptionalAttendees", "Resources"}
	touched := false
	for _, group := range groups {
		touched = touched || fields.has(group)
	}
	if !touched {
		return
	}
	organizerProp := master.Props.Get(ical.PropOrganizer)
	if organizerProp != nil && !profile.owns(calendar.MailAddress(organizerProp.Value)) {
		return
	}
	organizer := ""
	if organizerProp != nil {
		organizer = calendar.MailAddress(organizerProp.Value)
	}
	previous := map[string]ical.Prop{}
	var kept []ical.Prop
	for _, attendee := range master.Props.Values(ical.PropAttendee) {
		address := calendar.MailAddress(attendee.Value)
		previous[address] = attendee
		if address == organizer || !fields.has(attendeeGroup(attendee.Params)) {
			kept = append(kept, attendee)
		}
	}
	for _, group := range groups {
		list := fields.set[group]
		if list == nil {
			continue
		}
		for _, attendee := range list.ChildrenNamed("Attendee") {
			address := strings.ToLower(strings.TrimSpace(attendee.descendantText("EmailAddress")))
			if address == "" || address == organizer || slices.ContainsFunc(kept, func(prop ical.Prop) bool { return calendar.MailAddress(prop.Value) == address }) {
				continue
			}
			prop, ok := previous[address]
			if !ok {
				prop = *ical.NewProp(ical.PropAttendee)
				prop.Value = "mailto:" + address
				prop.Params.Set(ical.ParamParticipationStatus, "NEEDS-ACTION")
				prop.Params.Set(ical.ParamRSVP, "TRUE")
			}
			if name := strings.TrimSpace(attendee.descendantText("Name")); name != "" && !strings.EqualFold(name, address) {
				prop.Params.Set(ical.ParamCommonName, name)
			}
			prop.Params.Del(ical.ParamCalendarUserType)
			switch group {
			case "OptionalAttendees":
				prop.Params.Set(ical.ParamRole, "OPT-PARTICIPANT")
			case "Resources":
				prop.Params.Set(ical.ParamCalendarUserType, "RESOURCE")
				prop.Params.Set(ical.ParamRole, "NON-PARTICIPANT")
			default:
				prop.Params.Set(ical.ParamRole, "REQ-PARTICIPANT")
			}
			kept = append(kept, prop)
		}
	}
	master.Props.Del(ical.PropAttendee)
	others := 0
	for index := range kept {
		master.Props.Add(&kept[index])
		if calendar.MailAddress(kept[index].Value) != organizer {
			others++
		}
	}
	if others == 0 {
		master.Props.Del(ical.PropOrganizer)
		master.Props.Del(ical.PropAttendee)
		return
	}
	if organizerProp == nil && profile.primary() != "" {
		prop := ical.NewProp(ical.PropOrganizer)
		prop.Value = "mailto:" + profile.primary()
		if profile.DisplayName != "" {
			prop.Params.Set(ical.ParamCommonName, profile.DisplayName)
		}
		master.Props.Set(prop)
	}
}

// override returns the RECURRENCE-ID component for key, creating it from
// the master when the instance has no exception yet.
func (e *eventData) override(found occurrence, zone *time.Location) *ical.Component {
	if found.override != nil {
		return found.override
	}
	_, _, allDay, location, _ := componentTimes(e.master, zone)
	clone := ical.NewEvent()
	clone.Props = calendar.CloneProps(e.master.Props)
	for _, name := range []string{ical.PropRecurrenceRule, ical.PropExceptionDates, ical.PropRecurrenceDates} {
		clone.Props.Del(name)
	}
	for _, child := range e.master.Children {
		if child.Name == ical.CompAlarm {
			alarm := ical.NewComponent(ical.CompAlarm)
			alarm.Props = calendar.CloneProps(child.Props)
			clone.Children = append(clone.Children, alarm)
		}
	}
	recurrence := ical.NewProp(ical.PropRecurrenceID)
	if allDay {
		recurrence.SetDate(found.original)
	} else {
		recurrence.SetDateTime(found.original.In(location))
	}
	clone.Props.Set(recurrence)
	setEventTimes(clone.Props, found.start, found.end, allDay, location)
	e.cal.Children = append(e.cal.Children, clone.Component)
	e.overrides = append(e.overrides, clone.Component)
	return clone.Component
}

// deleteOccurrence excludes one instance: its override is dropped and an
// EXDATE added to the master.
func (e *eventData) deleteOccurrence(found occurrence, zone *time.Location, profile Profile) {
	_, _, allDay, location, _ := componentTimes(e.master, zone)
	if found.override != nil {
		e.cal.Children = slices.DeleteFunc(e.cal.Children, func(child *ical.Component) bool { return child == found.override })
		e.overrides = slices.DeleteFunc(e.overrides, func(child *ical.Component) bool { return child == found.override })
	}
	prop := ical.NewProp(ical.PropExceptionDates)
	if allDay {
		prop.SetDate(found.original)
	} else {
		prop.SetDateTime(found.original.In(location))
	}
	e.master.Props.Add(prop)
	if ownsOrganizer(e.master, profile) {
		current := 0
		if sequence := e.master.Props.Get(ical.PropSequence); sequence != nil {
			current, _ = sequence.Int()
		}
		sequence := ical.NewProp(ical.PropSequence)
		sequence.Value = strconv.Itoa(current + 1)
		e.master.Props.Set(sequence)
	}
	e.master.Props.SetDateTime(ical.PropDateTimeStamp, time.Now().UTC())
}

// setPartStat records the user's answer on its attendee entries.
func setPartStat(event *eventData, profile Profile, partStat string) bool {
	changed := false
	for _, component := range append([]*ical.Component{event.master}, event.overrides...) {
		for index := range component.Props[ical.PropAttendee] {
			attendee := &component.Props[ical.PropAttendee][index]
			if profile.owns(calendar.MailAddress(attendee.Value)) {
				attendee.Params.Set(ical.ParamParticipationStatus, partStat)
				attendee.Params.Del(ical.ParamRSVP)
				changed = true
			}
		}
	}
	return changed
}

func bodyText(body *node) string {
	text := body.Text
	if strings.EqualFold(body.attr("BodyType"), "HTML") {
		return service.HTMLToText(text)
	}
	return strings.ReplaceAll(text, "\r\n", "\n")
}

func stringList(list *node) []string {
	var values []string
	for _, child := range list.Children {
		if value := strings.TrimSpace(child.Text); value != "" {
			values = append(values, value)
		}
	}
	return values
}

func parseBool(value string) bool {
	value = strings.TrimSpace(value)
	return strings.EqualFold(value, "true") || value == "1"
}
