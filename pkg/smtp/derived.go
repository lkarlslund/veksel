package smtp

import (
	"context"
	"crypto/sha256"
	"fmt"
	"strings"

	"github.com/lkarlslund/veksel/pkg/model"
)

// DerivedRecipientResolver reports whether a generated message has a local
// destination. Backend failures must be returned rather than interpreted as an
// external address.
type DerivedRecipientResolver func(context.Context, string) (folderID, ownerID string, local bool, err error)

// PrepareDerivedMessage converts generated mail into durable queue work. The
// identity is deterministic within its parent/correlation scope so replaying a
// preparation cannot create a second queue record.
func PrepareDerivedMessage(ctx context.Context, derived DerivedMessage, resolve DerivedRecipientResolver) (*MailMessage, error) {
	if err := validateEmailAddress(derived.Recipient); err != nil {
		return nil, err
	}
	headers, _ := model.ParseMessageHeaders(derived.FullMessage)
	seed := strings.Join([]string{derived.Kind, derived.ParentID, derived.CorrelationID, strings.ToLower(derived.Recipient), string(derived.FullMessage)}, "\x00")
	digest := sha256.Sum256([]byte(seed))
	message := &MailMessage{ID: fmt.Sprintf("derived-%x", digest), CorrelationID: derived.CorrelationID, ParentID: derived.ParentID,
		Recipient: derived.Recipient, EnvelopeSender: derived.EnvelopeSender, Headers: headers, Outbound: true, DKIM: derived.DKIM,
		// The generated bytes are sent as they are, so a forward keeps the
		// original message's Received fields and their order.
		Content: append([]byte(nil), derived.FullMessage...)}
	// A forward carries the original envelope sender, so a forwarded bounce
	// keeps the null sender instead of borrowing a header identity.
	if message.EnvelopeSender == "" && derived.Kind != "forward" {
		message.EnvelopeSender = smtpHeaderValue(headers, "Return-Path")
	}
	if message.EnvelopeSender == "" && derived.Kind != "forward" {
		message.EnvelopeSender = smtpHeaderValue(headers, "From")
	}
	if resolve == nil {
		return message, nil
	}
	folderID, ownerID, local, err := resolve(ctx, derived.Recipient)
	if err != nil {
		return nil, fmt.Errorf("resolve derived recipient: %w", err)
	}
	if local {
		if folderID == "" || ownerID == "" {
			return nil, fmt.Errorf("resolve derived recipient: local destination is incomplete")
		}
		message.TargetFolderID, message.TargetOwnerID = folderID, ownerID
		// Local deliveries keep the generated bytes unsigned.
		message.Outbound, message.DKIM = false, nil
	}
	return message, nil
}
